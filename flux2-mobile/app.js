/* ---------------- settings (this device only) ---------------- */
function safeGet(k, d = "") { try { return localStorage.getItem(k) ?? d; } catch { return d; } }
function safeSet(k, v) { try { localStorage.setItem(k, v); } catch {} }
const settings = {
  get key() { return safeGet("bfl_key").trim(); },
  get model() { return safeGet("bfl_model", "flux-2-klein-4b"); },
  get relay() { return safeGet("bfl_relay").trim().replace(/\/+$/, ""); },
};

/* ---------------- IndexedDB gallery ---------------- */
let dbp;
function db() {
  dbp ??= new Promise((resolve, reject) => {
    const req = indexedDB.open("flux2-studio", 1);
    req.onupgradeneeded = () => req.result.createObjectStore("images", { keyPath: "id" });
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
  return dbp;
}
async function tx(mode, fn) {
  const d = await db();
  return new Promise((resolve, reject) => {
    const t = d.transaction("images", mode);
    const out = fn(t.objectStore("images"));
    t.oncomplete = () => resolve(out?.result ?? out);
    t.onerror = () => reject(t.error);
    t.onabort = () => reject(t.error || new Error("Storage is full. Delete some images and try again."));
  });
}
const dbAll = () => tx("readonly", (s) => s.getAll());
const dbPut = (item) => tx("readwrite", (s) => s.put(item));
const dbDel = (id) => tx("readwrite", (s) => s.delete(id));

function urlFor(blob) {
  if (!state.urls.has(blob)) state.urls.set(blob, URL.createObjectURL(blob));
  return state.urls.get(blob);
}

/* ---------------- small helpers ---------------- */
function el(tag, attrs = {}, ...kids) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === "class") n.className = v;
    else if (k.startsWith("on")) n.addEventListener(k.slice(2), v);
    else n.setAttribute(k, v);
  }
  n.append(...kids);
  return n;
}
