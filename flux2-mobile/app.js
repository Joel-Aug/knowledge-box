/* Shrink an image file to a JPEG (max 1536px) so uploads are quick on mobile data. */
async function toJpeg(blob, maxSide = 1536, quality = 0.9) {
  const bmp = await createImageBitmap(blob);
  const scale = Math.min(1, maxSide / Math.max(bmp.width, bmp.height));
  const c = document.createElement("canvas");
  c.width = Math.round(bmp.width * scale);
  c.height = Math.round(bmp.height * scale);
  c.getContext("2d").drawImage(bmp, 0, 0, c.width, c.height);
  bmp.close?.();
  return new Promise((r) => c.toBlob(r, "image/jpeg", quality));
}
function blobToBase64(blob) {
  return new Promise((resolve, reject) => {
    const fr = new FileReader();
    fr.onload = () => resolve(String(fr.result).split(",")[1]);
    fr.onerror = () => reject(fr.error);
    fr.readAsDataURL(blob);
  });
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/* ---------------- BFL API ---------------- */
class NetworkBlocked extends Error {}

// With a relay configured, every request goes to  <relay>/?url=<real BFL url>
function via(url) {
  return settings.relay ? `${settings.relay}/?url=${encodeURIComponent(url)}` : url;
}
async function call(url, opts = {}) {
  try {
    return await fetch(via(url), opts);
  } catch (e) {
    // fetch() only throws (rather than returning an error status) when the
    // request never got a readable answer: offline, or blocked by the browser.
    if (!navigator.onLine) throw new Error("You're offline. Connect to the internet and try again.");
    throw new NetworkBlocked(e.message);
  }
}

async function bflGenerate({ prompt, width, height, seed, refBlobs }) {
  const body = { prompt, width, height, seed, output_format: "png" };
  for (let i = 0; i < refBlobs.length; i++) {
    body[i === 0 ? "input_image" : `input_image_${i + 1}`] = await blobToBase64(refBlobs[i]);
  }
  const headers = { "x-key": settings.key, "Content-Type": "application/json", accept: "application/json" };
  const r = await call(`${BFL_BASE}/${settings.model}`, { method: "POST", headers, body: JSON.stringify(body) });
  if (r.status === 401 || r.status === 403) throw new Error("BFL rejected your API key. Check it in Settings (⚙︎).");
  if (r.status === 402) throw new Error("Your BFL account is out of credits. Top up at dashboard.bfl.ai.");
  if (r.status === 429) throw new Error("Too many requests at once. Wait a moment and try again.");
  if (r.status === 404) throw new Error(`BFL doesn't recognise the model “${settings.model}”. Pick another in Settings.`);
  if (!r.ok) throw new Error(`BFL error ${r.status}: ${(await r.text()).slice(0, 200)}`);
  const job = await r.json();
  const pollUrl = job.polling_url || `${BFL_BASE}/get_result?id=${job.id}`;

  const deadline = Date.now() + 180_000;
  while (Date.now() < deadline) {
    await sleep(800);
    const p = await call(pollUrl, { headers: { "x-key": settings.key, accept: "application/json" } });
    if (!p.ok) throw new Error(`BFL polling error ${p.status}`);
    const data = await p.json();
    if (data.status === "Ready") {
      // The result link expires after ~10 minutes, so store the image itself.
      const img = await call(data.result.sample);
      if (!img.ok) throw new Error(`Couldn't download the image (${img.status}).`);
      return await img.blob();
    }
    if (["Pending", "Queued", "Processing"].includes(data.status)) continue;
    if (/moderated/i.test(data.status || "")) throw new Error("Blocked by BFL's content filter. Try rewording the prompt.");
    throw new Error(`Generation failed (status: ${data.status}).`);
  }
  throw new Error("Timed out waiting for BFL. Try again.");
}

/* ---------------- Create tab ---------------- */
function setAspect(name) {
  state.aspect = name;
  document.querySelectorAll("#aspects button").forEach((b) => b.classList.toggle("active", b.dataset.ar === name));
}
function applyPreset(p) {
  const box = $("#prompt");
  if (box.value.trim() && box.value !== p.prompt && !confirm("Replace the current prompt with this template?")) return;
  box.value = p.prompt;
  setAspect(p.aspect);
  document.querySelectorAll("#presets button").forEach((b) => b.classList.toggle("active", b.dataset.id === p.id));
  const a = p.prompt.indexOf("["), z = p.prompt.indexOf("]", a);
  box.focus();
  if (a >= 0 && z > a) box.setSelectionRange(a, z + 1);
}

async function addRefs(files) {
  for (const f of files) {
    if (!f.type.startsWith("image/")) continue;
    if (state.refs.length >= MAX_REFS) { setStatus(`Up to ${MAX_REFS} reference images.`, true); break; }
    try {
      state.refs.push(await toJpeg(f));
    } catch {
      setStatus(`Couldn't read “${f.name}”. Try a JPG or PNG.`, true);
    }
  }
  renderRefs();
}
function renderRefs() {
  const list = $("#ref-list");
  list.innerHTML = "";
  state.refs.forEach((b, i) => {
    list.append(el("div", { class: "ref-item" },
      el("img", { src: urlFor(b), alt: `Reference ${i + 1}` }),
      el("span", { class: "num" }, `image ${i + 1}`),
      el("button", { class: "rm", type: "button", "aria-label": "Remove", onclick: () => { state.refs.splice(i, 1); renderRefs(); } }, "×")));
  });
}

async function generate() {
  const prompt = $("#prompt").value.trim();
  if (!settings.key) { openSettings(); return; }
  if (!prompt) { setStatus("Please enter a prompt first.", true); return; }

  const [width, height] = ASPECTS[state.aspect];
  const seedTxt = $("#seed").value.trim();
  const seed = /^\d+$/.test(seedTxt) ? Number(seedTxt) : Math.floor(Math.random() * 2 ** 31);
  const refBlobs = [...state.refs];

  const btn = $("#generate");
  btn.disabled = true;
  const t0 = Date.now();
  const tick = setInterval(() => setStatus(`Generating… ${Math.round((Date.now() - t0) / 1000)}s`), 500);
  setStatus("Generating…");

  try {
    const blob = await bflGenerate({ prompt, width, height, seed, refBlobs });
    const item = {
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
      blob, prompt, aspect: state.aspect, width, height, seed,
      model: settings.model, refs: refBlobs, created: new Date().toISOString(),
    };
    await dbPut(item);
    state.gallery.unshift(item);
    renderGallery();
    setStatus(`Done in ${Math.round((Date.now() - t0) / 1000)}s`);
    openViewer(item);
  } catch (e) {
    if (e instanceof NetworkBlocked) {
      setStatus(settings.relay
        ? "Couldn't reach your relay. Check the Relay URL in Settings, and that the relay is deployed."
        : "Your browser isn't allowed to talk to BFL directly. Set up the free relay (see the setup guide, step 4), then paste its URL in Settings.", true);
    } else setStatus(e.message, true);
  } finally {
    clearInterval(tick);
    btn.disabled = false;
  }
}

/* ---------------- Gallery ---------------- */
function renderGallery() {
  const g = $("#gallery");
  g.innerHTML = "";
  for (const item of state.gallery) {
    g.append(el("button", { class: "card", type: "button", onclick: () => openViewer(item) },
      el("img", { src: urlFor(item.blob), alt: "", loading: "lazy" }),
      el("div", { class: "cap" }, item.prompt)));
  }
  $("#count").textContent = state.gallery.length ? `(${state.gallery.length})` : "";
  $("#empty").classList.toggle("hidden", state.gallery.length > 0);
}

function openViewer(item) {
  state.current = item;
  $("#viewer-img").src = urlFor(item.blob);
  $("#viewer-prompt").textContent = item.prompt;
  const when = new Date(item.created).toLocaleString();
  $("#viewer-meta").textContent = `${item.aspect} · ${item.width}×${item.height} · seed ${item.seed} · ${item.model} · ${when}`;
  const refs = $("#viewer-refs");
  refs.innerHTML = "";
  if (item.refs?.length) {
    refs.append(el("span", { class: "muted small" }, "References:"));
    for (const r of item.refs) refs.append(el("img", { src: urlFor(r), alt: "reference" }));
  }
  $("#viewer").showModal();
}

async function shareCurrent() {
  const it = state.current;
  const file = new File([it.blob], `flux-${it.id}.png`, { type: "image/png" });
  if (navigator.canShare?.({ files: [file] })) {
    try { await navigator.share({ files: [file], text: it.prompt }); } catch {}
    return;
  }
  const a = el("a", { href: urlFor(it.blob), download: file.name });
  document.body.append(a);
  a.click();
  a.remove();
}

/* ---------------- Settings ---------------- */
async function openSettings() {
  $("#s-key").value = settings.key;
  $("#s-model").value = settings.model;
  $("#s-relay").value = settings.relay;
  const info = $("#storage-info");
  info.textContent = "";
  if (navigator.storage?.estimate) {
    const { usage } = await navigator.storage.estimate();
    info.textContent = `Gallery uses about ${(usage / 1e6).toFixed(1)} MB on this phone.`;
  }
  $("#settings").showModal();
}
$("#settings").addEventListener("close", () => {
  if ($("#settings").returnValue !== "save") return;
  safeSet("bfl_key", $("#s-key").value.trim());
  safeSet("bfl_model", $("#s-model").value);
  safeSet("bfl_relay", $("#s-relay").value.trim());
  refreshBanner();
  setStatus("Settings saved.");
});

/* ---------------- wiring ---------------- */
function init() {
  for (const p of PRESETS) {
    $("#presets").append(el("button", { type: "button", "data-id": p.id, onclick: () => applyPreset(p) }, p.name));
  }
  for (const [name, [w, h]] of Object.entries(ASPECTS)) {
    $("#aspects").append(el("button", { type: "button", "data-ar": name, title: `${w} × ${h}`, onclick: () => setAspect(name) }, name));
  }
  setAspect("1:1");

  document.querySelectorAll(".tab").forEach((t) => t.addEventListener("click", () => showTab(t.dataset.tab)));
  $("#open-settings").addEventListener("click", openSettings);
  $("#ref-input").addEventListener("change", (e) => { addRefs([...e.target.files]); e.target.value = ""; });
  $("#generate").addEventListener("click", generate);
  $("#prompt").addEventListener("keydown", (e) => { if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) generate(); });

  $("#v-close").addEventListener("click", () => $("#viewer").close());
  $("#viewer").addEventListener("click", (e) => { if (e.target.id === "viewer") $("#viewer").close(); });
  $("#v-share").addEventListener("click", shareCurrent);
  $("#v-reuse").addEventListener("click", () => {
    const it = state.current;
    $("#prompt").value = it.prompt;
    setAspect(it.aspect);
    $("#seed").value = it.seed;
    $("#viewer").close();
    showTab("create");
  });
  $("#v-ref").addEventListener("click", async () => {
    await addRefs([new File([state.current.blob], "result.png", { type: "image/png" })]);
    $("#viewer").close();
    showTab("create");
  });
  $("#v-delete").addEventListener("click", async () => {
    if (!confirm("Delete this image? This can't be undone.")) return;
    const it = state.current;
    await dbDel(it.id);
    state.gallery = state.gallery.filter((x) => x.id !== it.id);
    renderGallery();
    $("#viewer").close();
  });

  refreshBanner();
  dbAll()
    .then((items) => { state.gallery = items.sort((a, b) => b.created.localeCompare(a.created)); renderGallery(); })
    .catch(() => banner("This browser won't let the app store images (private browsing?). Generated images can't be kept."));

  // Ask the browser not to clear the gallery when space runs low.
  navigator.storage?.persist?.().catch(() => {});
  if ("serviceWorker" in navigator) navigator.serviceWorker.register("sw.js").catch(() => {});
}
init();
